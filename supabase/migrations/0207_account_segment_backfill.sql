-- 顧客の業種(industry)とセグメント(segment_id)のバックフィル（623社）
--
-- 背景:
--   顧客分析マトリクスで未分類が 672/784 社あり、原因は accounts.industry が
--   763社中671社で空だったこと。案件の「事前リサーチ」テキストには自社が
--   調査・記録した業種が一次情報として残っていたため、それを根拠に1社ずつ判定した。
--   社名からの推測はしていない。根拠が読み取れなかった社は本ファイルに含めず
--   未分類のまま残している（適用後の未分類は 125社）。
--
-- 判定の根拠例:
--   「トヨタグループの大手自動車部品メーカー」→ 製造
--   「福島県の民放テレビ局」               → 広告・メディア
--   「輸入小麦のサイロ事業・港湾運送企業」  → 物流・運輸
--   展示会リストの構造化行「業種/規模/地域: 建設・工事」がある社はそれを優先。
--
-- 新規セグメント3件（既存12分類に収まらない領域）:
--   通信・インフラ   … KDDI/JCOM/NTT東西/ケーブルテレビ局 など
--   エネルギー・環境 … ENEOS/関西電力/廃棄物処理・リサイクル など
--   官公庁・公共     … 市役所/国立研究開発法人/自衛隊/財団法人 など
--   ※ sort_order は既存12件(10〜120)より後ろの130〜150。キーワードの自動マッピングは
--     sort_order 昇順で先勝ちのため、既存セグメントの判定結果を変えない。
--
-- 冪等性:
--   segment_id が未設定の行だけを対象にするため、再実行しても手動で付け替えた
--   分類を上書きしない。id は先頭8桁で指定（本テナントの790社で一意であることを確認済み）。
--
-- 適用状況:
--   セグメント追加は apply_migration、UPDATE は行数の都合で execute_sql を3分割して
--   本番適用済み。DBの状態と本ファイルの内容は一致している。
-- =====================================================================

